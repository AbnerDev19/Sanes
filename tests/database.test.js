import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';

test('database enforces customer isolation, server prices, minimums and idempotency',async()=>{
 const db=new PGlite();
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create schema auth;create table auth.users(id uuid primary key,email text,email_confirmed_at timestamptz);
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to anon,authenticated;
 create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id uuid primary key,bucket_id text,name text);alter table storage.objects enable row level security;`);
 await db.exec(await readFile(new URL('../supabase/migrations/202611170001_store.sql',import.meta.url),'utf8'));
 const A='00000000-0000-4000-8000-000000000001',B='00000000-0000-4000-8000-000000000002',C='00000000-0000-4000-8000-000000000003';
 await db.query(`insert into auth.users values($1,'a@example.com',now()),($2,'b@example.com',now()),($3,'store@example.com',now())`,[A,B,C]);
 await db.exec(`insert into public.products(id,name,category,min_qty,unit_price) values('SB-001','Garrafa','Térmicos',30,12.50);insert into public.products(id,name,category,active) values('HIDDEN','Inativo','Teste',false);`);
 await db.query('insert into public.store_members values($1,\'owner\')',[C]);
 const login=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']);await db.exec(`set role ${id?'authenticated':'anon'}`)};
 await login(null);assert.equal((await db.query('select * from public.products')).rows.length,1);
 await assert.rejects(db.exec('select * from public.orders'),/permission denied/);
 await login(A);
 await assert.rejects(db.query('insert into public.carts(user_id,items) values($1,\'[]\')',[B]),/row-level security/);
 await assert.rejects(db.query('insert into public.store_members values($1,\'owner\')',[A]),/permission denied/);
 const customer={name:'Ana',email:'forged@example.com',company:'Empresa',phone:'61999990000',city:'Brasília',notes:'Arte por WhatsApp'};
 const item={id:'SB-001',qty:30,color:'Azul',method:'Laser',text:'Marca',unit_price:0};
 const place=(key,items)=>db.query('select public.place_order($1,$2,$3) as result',[key,JSON.stringify(items),JSON.stringify(customer)]);
 await assert.rejects(place('10000000-0000-4000-8000-000000000001',[{...item,qty:1}]),/Quantidade fora/);
 await assert.rejects(place('10000000-0000-4000-8000-000000000002',[{...item,id:'HIDDEN'}]),/não está disponível/);
 const request='10000000-0000-4000-8000-000000000003';
 const order=(await place(request,[item])).rows[0].result;
 assert.equal(Number(order.estimated_total),375);assert.equal(order.customer.email,'a@example.com');assert.equal(order.order_items.length,1);assert.equal(Number(order.order_items[0].unit_price),12.50);
 const duplicate=(await place(request,[item])).rows[0].result;assert.equal(duplicate.id,order.id);assert.equal(duplicate.order_items.length,1);
 assert.equal((await db.query('select * from public.orders')).rows.length,1);
 await assert.rejects(db.query("update public.orders set status='confirmed' where id=$1",[order.id]),/permission denied/);
 await assert.rejects(db.query("select public.update_order_status($1,'confirmed')",[order.id]),/restrito/);
 await login(B);assert.equal((await db.query('select * from public.orders')).rows.length,0);assert.equal((await db.query('select * from public.order_items')).rows.length,0);
 await login(C);assert.equal((await db.query('select * from public.orders')).rows.length,1);
 await db.query("select public.update_order_status($1,'in_contact')",[order.id]);
 assert.equal((await db.query('select status from public.orders where id=$1',[order.id])).rows[0].status,'in_contact');
 await db.close();
});
